defmodule Mica.RuntimeConfig.Snapshot do
  @moduledoc """
  Evaluates a runtime config file against a fixed set of environment variables
  and renders the result as stable text, so a change in what an environment
  gets shows up as a diff.

  The process environment is replaced by the fixture for the duration of the
  evaluation and restored afterwards, so callers must not run concurrently.
  """

  @header "# Generated by `mix config.snapshot --update`. Do not edit by hand.\n"

  @doc """
  Reads a fixture file with `NAME=value` lines. Blank lines and lines starting
  with `#` are skipped; the value is everything after the first `=`.
  """
  def read_env_file(path) do
    path
    |> File.read!()
    |> String.split("\n")
    |> Enum.map(&String.trim/1)
    |> Enum.reject(&(&1 == "" or String.starts_with?(&1, "#")))
    |> Map.new(fn line ->
      [name, value] = String.split(line, "=", parts: 2)
      {name, value}
    end)
  end

  @doc """
  Evaluates `runtime_path` for `config_env` with exactly the variables in `env`.

  The file is evaluated from a copy in a temporary directory, so paths relative
  to it (such as a local `.env`) do not leak a developer's machine into the
  result.
  """
  def evaluate(runtime_path, env, config_env) when is_map(env) do
    dir = Path.join(System.tmp_dir!(), "runtime_config_#{System.unique_integer([:positive])}")
    copy = Path.join([dir, "config", "runtime.exs"])
    File.mkdir_p!(Path.dirname(copy))
    File.cp!(runtime_path, copy)

    saved = System.get_env()

    try do
      replace_env(env)
      Config.Reader.read!(copy, env: config_env, target: :host)
    after
      replace_env(saved)
      File.rm_rf!(dir)
    end
  end

  @doc "Renders an evaluated config as formatted, ordered Elixir terms."
  def render(config) do
    body =
      config
      |> normalize(0)
      |> inspect(
        pretty: true,
        limit: :infinity,
        printable_limit: :infinity,
        width: 98,
        custom_options: [sort_maps: true]
      )
      |> Code.format_string!()
      |> IO.iodata_to_binary()

    @header <> body <> "\n"
  end

  defp replace_env(env) do
    System.get_env() |> Map.keys() |> Enum.each(&System.delete_env/1)
    System.put_env(env)
  end

  # Applications and their keys are sorted, as are option lists deeper down.
  # Lists keyed by modules (such as Oban plugins) keep their order, because
  # order can matter there.
  defp normalize(list, depth) when is_list(list) do
    list = Enum.map(list, &normalize_element(&1, depth))

    if depth < 2 or options?(list), do: Enum.sort_by(list, &elem(&1, 0)), else: list
  end

  defp normalize(other, _depth), do: other

  defp normalize_element({key, value}, depth), do: {key, normalize(value, depth + 1)}
  defp normalize_element(other, depth), do: normalize(other, depth + 1)

  defp options?([]), do: false

  defp options?(list) do
    Enum.all?(list, fn
      {key, _} when is_atom(key) -> not module?(key)
      _ -> false
    end)
  end

  defp module?(atom), do: atom |> Atom.to_string() |> String.starts_with?("Elixir.")
end
