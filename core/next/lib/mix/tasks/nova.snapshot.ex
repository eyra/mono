defmodule Mix.Tasks.Nova.Snapshot do
  @shortdoc "Check or update the Nova migration snapshots of the compiled SaaS"

  @moduledoc """
  Captures what a SaaS build wires together, so that the Nova migration
  (plan step code-systems) can move routes, grants, handlers and SaaS config
  between modules and show that nothing changed. The snapshots per SaaS are
  committed in `next/test/snapshots/<saas>/`:

    * `routes.exs`: every route as `{verb, path, plug, plug_opts, helper, module}`,
      in router order
    * `permissions.exs`: `Core.Authorization.permission_map/0`
    * `signal.exs`: signal handlers (in order) and notifiers
    * `flags.exs`: the feature flags declared at compile time
    * `saas_config.exs`: start pages, menus, `:meta`, `UserAuth` pages, account
      and admin tab order
    * `counts.exs`: boundary allowlist size, `no route path` compile warnings and
      the files `CoreWeb.Router` is compile-connected to

  Config-derived snapshots read `config/config.exs` as a prod build would
  (`Config.Reader`, env `:prod`). Runtime config, Oban and the runtime flag list
  are covered by `mix config.snapshot`, not here.

      mix nova.snapshot                              # Next: fail on drift
      BUNDLE=self MIX_ENV=dev mix nova.snapshot      # Self: fail on drift
      mix nova.snapshot --update                     # rewrite the snapshots

  Self needs `MIX_ENV=dev`: `config/test.exs` pins `:bundle` to `:next`.

  Routes pass when the route set is identical and every two routes that can
  match the same request keep their relative order; other reordering is allowed.
  Everything else must be identical. Next is also checked in `mix test`
  (`next/test/snapshots/nova_snapshot_test.exs`), Self in the `snapshot-self` CI job.
  """

  use Mix.Task

  @dir "next/test/snapshots"
  @header "# Generated by `mix nova.snapshot --update`. Do not edit by hand.\n"
  @routes_header "# {verb, path, plug, plug_opts, helper, module}, in router order.\n"
  @router "mica/lib/core_web/router.ex"

  @impl true
  def run(args) do
    {opts, _, _} = OptionParser.parse(args, switches: [update: :boolean])
    Mix.Task.run("compile")

    saas = saas!()
    started = System.monotonic_time(:millisecond)

    failures =
      for {name, rendered} <- render(saas), reduce: [] do
        failures ->
          path = path(saas, name)

          case {compare(name, path, rendered), opts[:update]} do
            {:same, _} ->
              failures

            {_, true} ->
              File.mkdir_p!(Path.dirname(path))
              File.write!(path, rendered)
              Mix.shell().info("updated #{path}")
              failures

            {{:reordered, note}, _} ->
              Mix.shell().info(note)
              failures

            {{:differs, message}, _} ->
              [{path, message} | failures]
          end
      end

    ms = System.monotonic_time(:millisecond) - started
    Mix.shell().info("nova.snapshot #{saas}: #{length(render_names())} snapshots in #{ms} ms")

    if failures != [] do
      Mix.raise("""
      #{Enum.map_join(Enum.reverse(failures), "\n", fn {path, message} -> "#{path}\n#{message}" end)}
      The #{saas} build differs from its Nova snapshots. If the change is intended,
      run `#{update_command(saas)}` and commit the reviewed diff.
      """)
    end
  end

  @doc "The SaaS the current build is for. Raises when config and `BUNDLE` disagree."
  def saas! do
    configured = Application.fetch_env!(:core, :bundle)
    requested = requested_bundle()

    if configured != requested do
      Mix.raise(
        "BUNDLE=#{requested} but the #{Mix.env()} config builds #{configured}; " <>
          "run Self with BUNDLE=self MIX_ENV=dev"
      )
    end

    configured
  end

  # Same rule as `.bundle.ex`, which is loaded by the config and not compiled.
  defp requested_bundle do
    default =
      case File.read(".bundle") do
        {:ok, bundle} -> String.trim(bundle)
        {:error, _} -> "next"
      end

    "BUNDLE" |> System.get_env(default) |> String.to_atom()
  end

  def path(saas, name), do: Path.join([@dir, to_string(saas), name])

  @doc "Compares one rendered snapshot with its committed file."
  def compare(name, path, rendered) do
    case File.read(path) do
      {:ok, ^rendered} -> :same
      {:ok, committed} when name == "routes.exs" -> compare_routes(committed, rendered)
      {:ok, committed} -> {:differs, diff(committed, rendered)}
      {:error, _} -> {:differs, "  missing"}
    end
  end

  defp update_command(:next), do: "mix nova.snapshot --update"
  defp update_command(saas), do: "BUNDLE=#{saas} MIX_ENV=dev mix nova.snapshot --update"

  defp render_names,
    do: ~w(routes.exs permissions.exs signal.exs flags.exs saas_config.exs counts.exs)

  @doc """
  Renders the snapshots of the current build as `{file name, text}`. `counts: false`
  leaves out `counts.exs`, which runs `mix compile` and `mix xref` in a subprocess.
  """
  def render(saas, opts \\ []) do
    prod = prod_config(saas)

    snapshots = [
      {"routes.exs", @routes_header <> format(routes())},
      {"permissions.exs", format(permissions())},
      {"signal.exs", format(signal(prod))},
      {"flags.exs", format(prod |> Keyword.get(:features, []) |> Enum.sort())},
      {"saas_config.exs", format(saas_config(prod))}
    ]

    snapshots =
      if Keyword.get(opts, :counts, true),
        do: snapshots ++ [{"counts.exs", format(counts())}],
        else: snapshots

    Enum.map(snapshots, fn {name, body} -> {name, @header <> body} end)
  end

  # --- snapshots

  defp routes do
    for route <- Phoenix.Router.routes(CoreWeb.Router) do
      {route.verb, route.path, route.plug, route.plug_opts, route.helper,
       Map.get(route.metadata, :log_module)}
    end
  end

  defp permissions do
    Core.Authorization.permission_map()
    |> Enum.map(fn {permission, roles} -> {permission, Enum.sort(roles)} end)
    |> Enum.sort()
  end

  defp signal(prod) do
    [
      handlers: prod |> Keyword.get(:signal, []) |> Keyword.get(:handlers),
      notifiers: prod |> Keyword.get(Systems.Notify, []) |> Keyword.get(:notifiers)
    ]
  end

  @saas_keys [
    :start_pages,
    :menu_items,
    :workspace_menu_builder,
    :website_menu_builder,
    :stripped_menu_builder,
    :meta,
    Systems.Account.UserAuth,
    :account,
    :pixel
  ]

  defp saas_config(prod) do
    Enum.map(@saas_keys, &{&1, Keyword.get(prod, &1)}) ++
      [
        account_tabs: Systems.Account.PageBuilder.tab_keys(),
        admin_tabs: Systems.Admin.ConfigPageBuilder.tab_ids()
      ]
  end

  defp counts do
    [
      boundary_allowlist: "boundary_allowlist.exs" |> Code.eval_file() |> elem(0) |> length(),
      no_route_path_warnings: no_route_path_warnings(),
      router_compile_connected: router_compile_connected()
    ]
  end

  # `--all-warnings` reprints the warnings stored in the manifest without recompiling.
  defp no_route_path_warnings do
    {output, 0} = mix(~w(compile --all-warnings))
    output |> String.split("\n") |> Enum.count(&String.contains?(&1, "no route path"))
  end

  # Files whose change recompiles the router (risks.md R2).
  defp router_compile_connected do
    {output, 0} =
      mix(~w(xref graph --no-compile --label compile-connected --source #{@router}))

    ~r/([\w\/.-]+\.exs?)/
    |> Regex.scan(output, capture: :all_but_first)
    |> List.flatten()
    |> Enum.reject(&(&1 == @router))
    |> Enum.uniq()
    |> Enum.sort()
  end

  defp mix(args), do: System.cmd("mix", args, stderr_to_stdout: true)

  # The `:core` config a prod build of `saas` compiles with.
  defp prod_config(saas) do
    saved = System.get_env("BUNDLE")
    System.put_env("BUNDLE", to_string(saas))

    try do
      "config/config.exs" |> Config.Reader.read!(env: :prod, target: :host) |> Keyword.get(:core)
    after
      if saved, do: System.put_env("BUNDLE", saved), else: System.delete_env("BUNDLE")
    end
  end

  # --- comparison

  defp format(term) do
    term
    |> inspect(
      pretty: true,
      limit: :infinity,
      printable_limit: :infinity,
      width: 98,
      custom_options: [sort_maps: true]
    )
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp compare_routes(committed, rendered) do
    {before, _} = Code.eval_string(committed)
    {now, _} = Code.eval_string(rendered)

    removed = before -- now
    added = now -- before
    swapped = overlap_order_changes(before, now)

    if removed == [] and added == [] and swapped == [] do
      {:reordered,
       "routes reordered without changing the order of overlapping routes; " <>
         "`--update` refreshes routes.exs"}
    else
      lines =
        Enum.map(removed, &"  - #{inspect(&1)}") ++
          Enum.map(added, &"  + #{inspect(&1)}") ++
          Enum.map(swapped, fn {a, b} ->
            "  order: #{route_label(a)} must stay before #{route_label(b)}"
          end)

      {:differs, Enum.join(lines, "\n")}
    end
  end

  defp route_label({verb, path, plug, _, _, _}), do: "#{verb} #{path} (#{inspect(plug)})"

  # Pairs of routes that can match the same request and changed relative order.
  defp overlap_order_changes(before, now) do
    position = now |> Enum.with_index() |> Enum.reverse() |> Map.new()
    shared = before |> Enum.filter(&Map.has_key?(position, &1)) |> Enum.uniq()

    for {a, i} <- Enum.with_index(shared),
        {b, j} <- Enum.with_index(shared),
        i < j,
        overlap?(a, b),
        position[a] > position[b],
        do: {a, b}
  end

  @doc "Whether two routes can match the same request."
  def overlap?({verb_a, path_a, _, _, _, _}, {verb_b, path_b, _, _, _, _}) do
    (verb_a == verb_b or :* in [verb_a, verb_b]) and
      segments_overlap?(segments(verb_a, path_a), segments(verb_b, path_b))
  end

  # A forward (verb :*) matches its path and everything below it.
  defp segments(:*, path), do: segments(nil, path) ++ ["*"]
  defp segments(_, path), do: String.split(path, "/", trim: true)

  defp segments_overlap?([], []), do: true
  defp segments_overlap?(["*" <> _ | _], _), do: true
  defp segments_overlap?(_, ["*" <> _ | _]), do: true
  defp segments_overlap?([], _), do: false
  defp segments_overlap?(_, []), do: false

  defp segments_overlap?([a | as], [b | bs]),
    do: (a == b or param?(a) or param?(b)) and segments_overlap?(as, bs)

  defp param?(segment), do: String.contains?(segment, ":")

  defp diff(committed, rendered) do
    committed
    |> String.split("\n")
    |> List.myers_difference(String.split(rendered, "\n"))
    |> Enum.flat_map(fn
      {:eq, lines} -> context(lines)
      {:del, lines} -> Enum.map(lines, &"  - #{&1}")
      {:ins, lines} -> Enum.map(lines, &"  + #{&1}")
    end)
    |> Enum.join("\n")
  end

  defp context(lines) when length(lines) <= 4, do: Enum.map(lines, &"    #{&1}")

  defp context(lines),
    do:
      Enum.map(Enum.take(lines, 2), &"    #{&1}") ++
        ["    ..."] ++ Enum.map(Enum.take(lines, -2), &"    #{&1}")
end
